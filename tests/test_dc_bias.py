"""Independent, hand-checked DC bias reference cases."""

import math
import unittest
from dataclasses import replace

import dc_bias
from dc_bias import BiasInputs, InputValidationError, _verify_result, calculate_bias


class BiasModelTests(unittest.TestCase):
    def setUp(self):
        self.default = BiasInputs(
            vcc_v=12.0, r1_ohm=100_000.0, r2_ohm=22_000.0,
            rc_ohm=2_200.0, re_ohm=1_000.0, beta=100.0, vbe_v=0.70,
        )

    def test_reference_forward_active(self):
        point = calculate_bias(self.default)
        self.assertEqual(point.region, "forward_active")
        for key, expected in {
            "VTH_V": 2.163934426, "RTH_OHM": 18032.786885,
            "VB_V": 1.942156728, "VE_V": 1.242156728,
            "VC_V": 9.294312078, "VCE_V": 8.052155351,
        }.items():
            self.assertAlmostEqual(point.values[key], expected, delta=1e-6, msg=key)
        for key, expected in {
            "IB_A": 12.298581463e-6,
            "IC_A": 1.229858146e-3,
            "IE_A": 1.242156728e-3,
        }.items():
            self.assertAlmostEqual(point.values[key], expected, delta=1e-10, msg=key)

    def test_cutoff_estimate_has_zero_transistor_current(self):
        point = calculate_bias(BiasInputs(
            vcc_v=5, r1_ohm=100_000, r2_ohm=1_000,
            rc_ohm=2_200, re_ohm=1_000, beta=100, vbe_v=0.70,
        ))
        self.assertEqual(point.region, "cutoff_estimate")
        self.assertAlmostEqual(point.values["VB_V"], 5 / 101, places=9)
        for key in ("IB_A", "IC_A", "IE_A", "VE_V"):
            self.assertEqual(point.values[key], 0.0)
        self.assertEqual(point.values["VC_V"], 5)
        self.assertTrue(any("estimate" in w.lower() for w in point.warnings))

    def test_divider_exact_cutoff_boundary_and_positive_headroom(self):
        # 1.1 × 3000 / 4000 is 0.825 exactly in the stated decimal inputs.
        params = BiasInputs(1.1, 1000, 3000, 2200, 1000, 100, .825)
        cutoff = calculate_bias(params)
        self.assertEqual(cutoff.region, "cutoff_estimate")
        self.assertEqual(cutoff.values["VTH_V"], .825)
        self.assertEqual(cutoff.values["IC_A"], 0.0)
        active = calculate_bias(replace(params, vbe_v=.8249999999999998))
        self.assertEqual(active.region, "forward_active")
        self.assertAlmostEqual(active.values["IB_A"], 2e-16 / 101750, delta=1e-32)

    def test_divider_does_not_round_the_vce_boundary_into_forward_active(self):
        # IB is 2 mA, VE is 0.4 V and VC is 0.6 V; VCE=0.20 V exactly.
        params = BiasInputs(3.0, 1000, 1000, 1200, 100, 1, .1)
        result = calculate_bias(params)
        self.assertEqual(result.region, "outside_model")
        self.assertIsNone(result.values["IC_A"])

    def test_divider_retains_representable_positive_vce_margin(self):
        # At RC = 1020 Ω, VCE = 0.20 V exactly. This adjacent lower RC raises it.
        params = BiasInputs(1.1, 1000, 1000, math.nextafter(1020.0, 0.0), 10, 1, .1)
        point = calculate_bias(params)
        self.assertEqual(point.region, "forward_active")
        self.assertEqual(point.values["VCE_V"], .2000000000000001)

    def test_saturation_estimate_respects_forced_beta(self):
        point = calculate_bias(BiasInputs(
            vcc_v=5, r1_ohm=10_000, r2_ohm=10_000,
            rc_ohm=10_000, re_ohm=1_000, beta=100, vbe_v=0.70,
        ))
        self.assertEqual(point.region, "saturation_estimate")
        self.assertAlmostEqual(point.values["VCE_V"], 0.20, places=8)
        self.assertGreater(point.values["IC_A"], 0)
        self.assertLessEqual(point.values["IC_A"], 100 * point.values["IB_A"])
        self.assertAlmostEqual(
            point.values["VC_V"] - point.values["VE_V"], 0.20, places=8,
        )
        self.assertTrue(any("estimate" in w.lower() for w in point.warnings))

    def test_tiny_saturation_currents_cannot_bypass_forced_beta_limit(self):
        # Independently derived saturation currents for these scaled
        # circuits satisfy IC/(beta*IB) ~= 1.956 > 1.0. An absolute
        # 1e-12 A allowance must not turn that physical violation into PASS.
        for scale in (1.0, 1e-6):
            with self.subTest(scale=scale):
                point = calculate_bias(BiasInputs(
                    vcc_v=1.4086,
                    r1_ohm=1e12 * scale, r2_ohm=1e12 * scale,
                    rc_ohm=1e12 * scale, re_ohm=1e9 * scale,
                    beta=100, vbe_v=0.7,
                ))
                self.assertEqual(point.region, "outside_model")
                self.assertIsNone(point.values["IC_A"])
                self.assertTrue(point.warnings)

    def test_saturation_high_resistance_ratio_avoids_cancellation(self):
        # Exact-KVL high-precision Decimal reference (not generated by
        # calculate_bias): VE ~= 4.29500495714 V, IB ~= 3.7900099143e-8 A,
        # IC ~= 5.0499504286e-9 A. Subtracting VTH-VBE-VE numerically
        # loses significant digits and used to reject this valid estimate.
        point = calculate_bias(BiasInputs(
            vcc_v=5.0, r1_ohm=1.0, r2_ohm=1_000.0,
            rc_ohm=1e8, re_ohm=1e8, beta=10.0, vbe_v=0.7,
        ))
        self.assertEqual(point.region, "saturation_estimate")
        self.assertAlmostEqual(
            point.values["IB_A"], 3.7900099143e-8, delta=5e-14,
        )
        self.assertAlmostEqual(
            point.values["IC_A"], 5.0499504286e-9, delta=5e-15,
        )
        self.assertAlmostEqual(
            point.values["VE_V"], 4.29500495714, delta=2e-8,
        )
        self.assertTrue(all(point.checks.values()), point.checks)

    def test_saturation_requires_base_collector_forward_bias(self):
        # VBE below assumed VCE(sat) makes VB < VC; calling this
        # "saturation" would violate the base-collector junction polarity.
        params = BiasInputs(
            vcc_v=5, r1_ohm=10_000, r2_ohm=10_000,
            rc_ohm=10_000, re_ohm=1_000, beta=100, vbe_v=0.10,
        )
        point = calculate_bias(params)
        self.assertEqual(point.region, "outside_model")
        self.assertIsNone(point.values["VB_V"])
        self.assertIsNone(point.values["VC_V"])
        self.assertIsNone(point.values["IC_A"])
        self.assertTrue(point.warnings)

    def test_reject_invalid_physical_or_nonfinite_inputs(self):
        base = vars(self.default).copy()
        for name, bad in (
            ("vcc_v", 0), ("vcc_v", -2),
            ("r1_ohm", 0), ("r2_ohm", -1),
            ("rc_ohm", 0), ("re_ohm", -1),
            ("beta", 0), ("beta", -5),
            ("vbe_v", 0), ("vbe_v", -0.7),
            ("vcc_v", math.nan), ("beta", math.inf),
            ("r1_ohm", 1e300),
        ):
            with self.subTest(name=name, bad=bad):
                values = dict(base, **{name: bad})
                with self.assertRaises(InputValidationError) as ctx:
                    calculate_bias(BiasInputs(**values))
                self.assertIn(name, ctx.exception.errors)

    def test_reject_boolean_and_huge_integer_direct_model_inputs(self):
        base = vars(self.default).copy()
        for name, bad in (
            ("vcc_v", True), ("r1_ohm", True), ("beta", True),
            ("vcc_v", 10**1000), ("r1_ohm", 10**1000),
            ("beta", 10**1000),
        ):
            with self.subTest(name=name, kind=type(bad).__name__):
                with self.assertRaises(InputValidationError) as ctx:
                    calculate_bias(BiasInputs(**dict(base, **{name: bad})))
                self.assertIn(name, ctx.exception.errors)

    def test_self_checks_cover_transistor_and_divider_kcl(self):
        cases = [self.default, BiasInputs(
            vcc_v=5, r1_ohm=10_000, r2_ohm=10_000,
            rc_ohm=10_000, re_ohm=1_000, beta=100, vbe_v=0.70,
        )]
        required = {
            "transistor_kcl", "divider_kcl", "collector_drop",
            "emitter_drop", "vce_identity", "region_consistency",
        }
        for params in cases:
            with self.subTest(vcc=params.vcc_v):
                point = calculate_bias(params)
                self.assertEqual(set(point.checks), required)
                self.assertTrue(all(point.checks.values()))

    def test_small_current_kcl_self_check_detects_relative_error(self):
        # In a high-resistance active circuit, a 0.05% IE corruption is
        # smaller than the old 1e-12 A absolute tolerance, but the
        # transistor KCL must reject it as an engineering inconsistency.
        params = BiasInputs(
            vcc_v=12, r1_ohm=1e12, r2_ohm=1e12,
            rc_ohm=2_200, re_ohm=1e9, beta=100, vbe_v=0.7,
        )
        original = calculate_bias(params)
        self.assertEqual(original.region, "forward_active")
        values = dict(original.values)
        values["IE_A"] += 5e-13
        checked = _verify_result(params, replace(original, values=values))
        self.assertFalse(checked.checks["transistor_kcl"])

    def test_divider_kcl_accepts_voltage_roundoff_without_masking_current_errors(self):
        # At R1=1 ohm and RE=10 Gohm, VCC-VB is roughly a nanovolt.
        # Subtraction at 24 V loses digits that cannot be recovered by
        # comparing 1 nA currents with only a relative tolerance.
        params = BiasInputs(
            vcc_v=24, r1_ohm=1, r2_ohm=1e10,
            rc_ohm=1, re_ohm=1e10, beta=1, vbe_v=0.7,
        )
        point = calculate_bias(params)
        self.assertEqual(point.region, "forward_active")
        self.assertTrue(point.checks["divider_kcl"])
        # A deliberate 1 µV base-voltage corruption is far larger than
        # the theoretical floating-point roundoff allowance.
        bad_values = dict(point.values)
        bad_values["VB_V"] += 1e-6
        corrupted = _verify_result(params, replace(point, values=bad_values))
        self.assertFalse(corrupted.checks["divider_kcl"])

    def test_active_region_rejects_beta_relation_corruption_even_if_kcl_balances(self):
        # Tiny changes to IB and IC in opposite directions keep IE=IB+IC.
        # Their voltage-drop effect may be below floating-point precision;
        # without IC=beta*IB a 400x transistor-gain mismatch passed all six
        # legacy checks as a supposedly valid forward-active Q-point.
        params = BiasInputs(
            vcc_v=24, r1_ohm=1, r2_ohm=1e12,
            rc_ohm=1, re_ohm=1e12, beta=1e6, vbe_v=0.7,
        )
        point = calculate_bias(params)
        self.assertEqual(point.region, "forward_active")
        bad = dict(point.values)
        bad["IB_A"] += 1e-14
        bad["IC_A"] -= 1e-14
        self.assertAlmostEqual(bad["IE_A"], bad["IB_A"] + bad["IC_A"], delta=1e-25)
        self.assertLess(bad["IC_A"] / (params.beta * bad["IB_A"]), 0.01)
        checked = _verify_result(params, replace(point, values=bad))
        self.assertEqual(checked.region, "outside_model")
        self.assertFalse(checked.checks["region_consistency"])
        self.assertIsNone(checked.values["IC_A"])

    def test_divider_kcl_ulps_bound_precision_not_arbitrary_current_floor(self):
        # With R1=1 ohm and VB nearly 24 V, the node-current calculation
        # resolves VCC-VB only to voltage ULPs. Characterize both sides of
        # that precision boundary; the oracle is the IEEE-754 ULP scale,
        # not another invocation of the divider KCL verifier.
        params = BiasInputs(24, 1, 1e12, 1, 1e12, 1e6, 0.7)
        point = calculate_bias(params)
        self.assertEqual(point.region, "forward_active")
        vb = point.values["VB_V"]
        one_ulp = math.ulp(vb)
        for delta, expected in ((one_ulp, True), (64 * one_ulp, False)):
            with self.subTest(delta=delta):
                bad = dict(point.values, VB_V=vb + delta)
                verified = _verify_result(params, replace(point, values=bad))
                self.assertEqual(verified.checks["divider_kcl"], expected)


class ThreeModeModelTests(unittest.TestCase):
    def setUp(self):
        self.fixed = dc_bias.FixedBiasInputs(12.0, 1e6, 2200.0, 100.0, 0.7)
        self.emitter = dc_bias.EmitterBiasInputs(12.0, 1e6, 2200.0, 1000.0, 100.0, 0.7)

    def assert_value_map(self, result, ib, ic, ie, vb, ve, vc, vce):
        expected = {
            "IB_A": ib, "IC_A": ic, "IE_A": ie,
            "VB_V": vb, "VE_V": ve, "VC_V": vc, "VCE_V": vce,
        }
        self.assertEqual(set(result.values), expected.keys() | {"VTH_V", "RTH_OHM"})
        self.assertIsNone(result.values["VTH_V"])
        self.assertIsNone(result.values["RTH_OHM"])
        for key, value in expected.items():
            with self.subTest(key=key):
                self.assertIsInstance(result.values[key], float)
                self.assertAlmostEqual(
                    result.values[key], value, delta=5e-15 if key.endswith("_A") else 5e-12,
                )

    def assert_check_shape(self, result, emitter_check):
        self.assertEqual(set(result.checks), {
            "transistor_kcl", "base_kvl", "collector_kvl", "collector_drop",
            emitter_check, "vce_identity", "region_consistency",
        })

    def assert_outside_model(self, result, emitter_check):
        self.assertEqual(result.region, "outside_model")
        self.assertTrue(all(value is None for value in result.values.values()))
        self.assertTrue(result.warnings)
        self.assert_check_shape(result, emitter_check)
        self.assertTrue(all(value is False for value in result.checks.values()))

    def test_fixed_bias_a2_grounded_emitter(self):
        result = dc_bias.calculate_fixed_bias(self.fixed)
        self.assertEqual(result.region, "forward_active")
        self.assert_value_map(result, 11.3e-6, 1.13e-3, 1.1413e-3, .7, 0.0, 9.514, 9.514)
        self.assert_check_shape(result, "emitter_ground")
        self.assertTrue(all(value is True for value in result.checks.values()))
        self.assertFalse(result.warnings)

    def test_emitter_bias_a3_a4_uses_re(self):
        first = dc_bias.calculate_emitter_bias(self.emitter)
        second = dc_bias.calculate_emitter_bias(replace(self.emitter, re_ohm=2000.0))
        cases = (
            (first, 10.263396911898e-6, 1.026339691190e-3, 1.036603088102e-3,
             1.736603088102, 1.036603088102, 9.742052679382, 8.705449591281),
            (second, 9.400998336106e-6, .940099833611e-3, .949500831947e-3,
             2.599001663894, 1.899001663894, 9.931780366057, 8.032778702163),
        )
        for result, *values in cases:
            self.assertEqual(result.region, "forward_active")
            self.assert_value_map(result, *values)
            self.assert_check_shape(result, "emitter_drop")
            self.assertTrue(all(value is True for value in result.checks.values()))
            self.assertFalse(result.warnings)
        self.assertLess(second.values["IC_A"], first.values["IC_A"])

    def test_direct_validation_uses_si_field_errors(self):
        cases = (
            (self.fixed, dc_bias.calculate_fixed_bias, "rb_ohm", 0.5),
            (self.fixed, dc_bias.calculate_fixed_bias, "rb_ohm", 0),
            (self.fixed, dc_bias.calculate_fixed_bias, "rb_ohm", 10**1000),
            (self.fixed, dc_bias.calculate_fixed_bias, "vcc_v", True),
            (self.emitter, dc_bias.calculate_emitter_bias, "rc_ohm", math.inf),
            (self.emitter, dc_bias.calculate_emitter_bias, "re_ohm", math.nan),
            (self.emitter, dc_bias.calculate_emitter_bias, "vbe_v", "0.7"),
        )
        for params, solver, key, value in cases:
            with self.subTest(key=key, solver=solver.__name__):
                with self.assertRaises(dc_bias.InputValidationError) as error:
                    solver(replace(params, **{key: value}))
                self.assertEqual(set(error.exception.errors), {key})
        dc_bias.validate_fixed_bias_inputs(replace(self.fixed, rb_ohm=1.0))
        dc_bias.validate_emitter_bias_inputs(replace(self.emitter, rb_ohm=1e12))

    def test_dispatch_requires_exact_mode_and_matching_input_type(self):
        divider = dc_bias.BiasInputs(12, 100000, 22000, 2200, 1000, 100, .70)
        for mode, params, solver in (
            ("fixed", self.fixed, dc_bias.calculate_fixed_bias),
            ("emitter", self.emitter, dc_bias.calculate_emitter_bias),
            ("divider", divider, dc_bias.calculate_bias),
        ):
            with self.subTest(mode=mode):
                self.assertEqual(dc_bias.calculate_by_mode(mode, params), solver(params))
        for mode, params in (
            ("fixed", self.emitter), ("emitter", self.fixed), ("divider", self.fixed),
            ("Fixed", self.fixed), ("", self.fixed), (None, self.fixed),
        ):
            with self.subTest(mode=mode):
                with self.assertRaises(dc_bias.InputValidationError) as error:
                    dc_bias.calculate_by_mode(mode, params)
                self.assertEqual(set(error.exception.errors), {"mode"})

    def test_fixed_rejects_forward_biased_bc_even_above_vce_floor(self):
        # 12 - 2200 * 100 * (12 - 0.7) / 215000 is about 0.437 V,
        # greater than the VCE floor and below the 0.7 V base.
        params = replace(self.fixed, rb_ohm=215_000.0)
        self.assert_outside_model(dc_bias.calculate_fixed_bias(params), "emitter_ground")

    def test_emitter_rejects_nonpositive_base_current_without_q_point(self):
        for vcc in (0.6, 0.7):
            with self.subTest(vcc=vcc):
                params = replace(self.emitter, vcc_v=vcc)
                self.assert_outside_model(dc_bias.calculate_emitter_bias(params), "emitter_drop")

    def test_forward_active_rejects_underflowed_positive_collector_current(self):
        params = replace(self.fixed, beta=math.nextafter(0.0, 1.0))
        self.assert_outside_model(dc_bias.calculate_fixed_bias(params), "emitter_ground")

    def test_strict_vce_floor_on_adjacent_floats(self):
        point = dc_bias.FixedBiasInputs(.375, 2.0, 1.0, 1.0, .025)
        for vcc in (math.nextafter(.375, 0.0), .375):
            with self.subTest(vcc=vcc):
                self.assert_outside_model(
                    dc_bias.calculate_fixed_bias(replace(point, vcc_v=vcc)), "emitter_ground",
                )
        above = dc_bias.calculate_fixed_bias(replace(point, vcc_v=math.nextafter(.375, math.inf)))
        self.assertEqual(above.region, "forward_active")
        self.assertEqual(above.values["VCE_V"], math.nextafter(.20, math.inf))

    def test_base_collector_junction_must_be_strictly_reverse_biased(self):
        point = dc_bias.FixedBiasInputs(2.0, 2.0, 2.0, 1.0, .5)
        self.assert_outside_model(dc_bias.calculate_fixed_bias(point), "emitter_ground")
        above = dc_bias.calculate_fixed_bias(replace(point, rb_ohm=math.nextafter(2.0, math.inf)))
        self.assertEqual(above.region, "forward_active")
        self.assertGreater(above.values["VC_V"], above.values["VB_V"])

    def test_base_kvl_verifies_returned_base_emitter_drop(self):
        for params, solver in (
            (self.fixed, dc_bias.calculate_fixed_bias), (self.emitter, dc_bias.calculate_emitter_bias),
        ):
            with self.subTest(solver=solver.__name__):
                values = solver(params).values.copy()
                values["VB_V"] += 1e-6
                checks = dc_bias._active_checks(params, values)
                self.assertFalse(checks["base_kvl"])
                self.assertTrue(checks["region_consistency"])

    def test_decimal_base_collector_equality_is_not_rounded_into_active(self):
        # IC = 1.13 mA exactly, so VC = 12 - 11.3 = VB = 0.70 V.
        params = dc_bias.FixedBiasInputs(12.0, 1e6, 1e4, 100.0, .7)
        point = dc_bias.calculate_fixed_bias(params)
        self.assertEqual(point.region, "outside_model")
        self.assertIsNone(point.values["IC_A"])

    def test_independent_check_detects_bad_fixed_ground_and_emitter_drop(self):
        fixed = dc_bias.calculate_fixed_bias(self.fixed).values.copy()
        fixed["VE_V"] = 1e-9
        self.assertFalse(dc_bias._active_checks(self.fixed, fixed)["emitter_ground"])
        emitter = dc_bias.calculate_emitter_bias(self.emitter).values.copy()
        emitter["VE_V"] *= 1.001
        self.assertFalse(dc_bias._active_checks(self.emitter, emitter)["emitter_drop"])

    def test_collector_drop_uses_returned_collector_voltage(self):
        values = dc_bias.calculate_emitter_bias(self.emitter).values.copy()
        values["VC_V"] *= 1.001
        self.assertFalse(dc_bias._active_checks(self.emitter, values)["collector_drop"])

    def test_transistor_kcl_catches_sub_picoampere_relative_error(self):
        params = replace(self.fixed, vcc_v=5.0, rb_ohm=1e12, rc_ohm=1.0)
        values = dc_bias.calculate_fixed_bias(params).values.copy()
        values["IE_A"] *= 1.0005
        self.assertFalse(dc_bias._active_checks(params, values)["transistor_kcl"])

    def test_region_check_catches_wrong_beta_when_transistor_kcl_balances(self):
        values = dc_bias.calculate_fixed_bias(self.fixed).values.copy()
        adjustment = values["IB_A"] / 2
        values["IB_A"] -= adjustment
        values["IC_A"] += adjustment
        checks = dc_bias._active_checks(self.fixed, values)
        self.assertFalse(checks["region_consistency"])
        self.assertTrue(checks["transistor_kcl"])
